/**
 * Builds the intro video's soundtrack: every line in video/narration.json is
 * spoken with a free macOS voice (`say`), placed at its start time, and mixed
 * over a soft background pad that dips while someone is talking.
 *
 *   npm run video:audio   → video/narration.m4a (npm run video then adds it to the MP4)
 *
 * macOS only (uses `say`). Needs ffmpeg.
 */
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const { rate, lines } = JSON.parse(readFileSync(resolve(root, "video/narration.json"), "utf8"));
const DURATION = 66;
const work = resolve(root, "video/voice");
rmSync(work, { recursive: true, force: true });
mkdirSync(work, { recursive: true });

// 1. Speak each line, and measure how loud it is in every video frame (for lip-sync).
const FPS = 30;
const RATE = 16000;
const timeline = [];
const clips = lines.map((line, i) => {
  const file = resolve(work, `line-${String(i).padStart(2, "0")}.aiff`);
  // `say` sometimes returns a cut-off or stretched take, so record until two takes match.
  const probe = (f) => Number(execFileSync("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", f]).toString());
  let previous = -1;
  for (let take = 0; take < 6; take++) {
    execFileSync("say", ["-v", line.voice, "-r", String(rate), "-o", file, line.text]);
    const length = probe(file);
    if (Math.abs(length - previous) < 0.03) break;
    previous = length;
  }
  const pcm = execFileSync("ffmpeg", ["-v", "error", "-i", file, "-ac", "1", "-ar", String(RATE), "-f", "f32le", "-"], { maxBuffer: 1 << 28 });
  const samples = new Float32Array(pcm.buffer, pcm.byteOffset, pcm.byteLength / 4);
  const perFrame = RATE / FPS;
  const levels = [];
  for (let f = 0; f * perFrame < samples.length; f++) {
    let sum = 0;
    const from = Math.floor(f * perFrame), to = Math.min(samples.length, Math.floor((f + 1) * perFrame));
    for (let s = from; s < to; s++) sum += samples[s] * samples[s];
    levels.push(Math.sqrt(sum / Math.max(1, to - from)));
  }
  const peak = Math.max(...levels) || 1;
  // 0 = mouth closed, 1 = wide open; quiet bits close the mouth.
  const env = levels.map((v) => Math.round(Math.min(1, Math.max(0, (v / peak - 0.08) * 1.4)) * 100) / 100);
  const seconds = samples.length / RATE;
  const end = line.start + seconds;
  const next = lines[i + 1]?.start ?? DURATION;
  console.log(`${line.start.toFixed(1).padStart(5)}–${end.toFixed(1).padEnd(5)} ${line.who.padEnd(16)} ${line.text}${end > next + 0.05 ? "   ⚠ runs into the next line" : ""}`);
  timeline.push({ start: line.start, end: Math.round(end * 100) / 100, who: line.who, text: line.text, env });
  return { file, start: line.start };
});
// The video page reads this to show speech bubbles and move mouths in time with the voices.
writeFileSync(resolve(root, "video/narration.js"), `// Generated by scripts/make-narration.mjs. Do not edit by hand.\nwindow.NARRATION = ${JSON.stringify(timeline)};\n`);

// 2. A soft, slowly moving chord (A minor 9) as background music, made by ffmpeg.
const pad = resolve(work, "pad.wav");
const notes = [110, 164.81, 220, 261.63, 329.63, 493.88];
const expr = notes.map((f, i) => `0.05*sin(2*PI*${f}*t)*(0.6+0.4*sin(2*PI*${0.07 + i * 0.03}*t+${i}))`).join("+");
execFileSync("ffmpeg", ["-v", "error", "-y", "-f", "lavfi", "-i", `aevalsrc=${expr}:s=44100:d=${DURATION}`,
  "-af", `lowpass=f=1800,afade=t=in:d=2,afade=t=out:st=${DURATION - 3}:d=3,volume=0.55`, pad]);

// 3. Place the voices, then duck the music under them.
const inputs = clips.flatMap((c) => ["-i", c.file]);
const delayed = clips.map((c, i) => `[${i + 1}:a]aresample=44100,adelay=${Math.round(c.start * 1000)}|${Math.round(c.start * 1000)},volume=1.6[v${i}]`).join(";");
const mixVoices = `${clips.map((_, i) => `[v${i}]`).join("")}amix=inputs=${clips.length}:normalize=0,apad=whole_dur=${DURATION}[voice]`;
const filter = `${delayed};${mixVoices};[voice]asplit=2[vk][vm];[0:a][vk]sidechaincompress=threshold=0.02:ratio=8:attack=20:release=400[music];[music][vm]amix=inputs=2:normalize=0,alimiter=limit=0.95,atrim=0:${DURATION}[out]`;
const out = resolve(root, "video/narration.m4a");
execFileSync("ffmpeg", ["-v", "error", "-y", "-i", pad, ...inputs, "-filter_complex", filter, "-map", "[out]", "-c:a", "aac", "-b:a", "160k", out]);
console.log(`Saved ${out}`);
